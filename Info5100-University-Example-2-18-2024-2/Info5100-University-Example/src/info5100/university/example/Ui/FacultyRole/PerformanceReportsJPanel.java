    private void btnGenerateReportActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerateReportActionPerformed
        // TODO add your handling code here:
        String term = (String) cmbSemester.getSelectedItem();
    String cid  = (String) cmbCourse.getSelectedItem();
    if (term == null || cid == null || "(none)".equals(cid)) {
        javax.swing.JOptionPane.showMessageDialog(this, "Pick a semester and one of your courses.");
        return;
    }
    info5100.university.example.CourseSchedule.CourseSchedule cs = ctx.getSchedule(term);
    if (cs == null) { javax.swing.JOptionPane.showMessageDialog(this, "Semester not found."); return; }

    info5100.university.example.CourseSchedule.CourseOffer co = cs.getCourseOfferByNumber(cid);
    if (co == null || co.getFacultyProfile() != faculty) {
        javax.swing.JOptionPane.showMessageDialog(this, "Course not found or not assigned to you.");
        return;
    }

    int enrolled = co.getEnrolledCount();

    javax.swing.table.DefaultTableModel m =
        (javax.swing.table.DefaultTableModel) tblReport.getModel();
    m.setRowCount(0);
    m.addRow(new Object[]{"Semester", term});
    m.addRow(new Object[]{"Course", cid});
    m.addRow(new Object[]{"Enrollment Count", Integer.valueOf(enrolled)});
    m.addRow(new Object[]{"Average Grade", "N/A"});
    m.addRow(new Object[]{"Grade A", Integer.valueOf(0)});
    m.addRow(new Object[]{"Grade B", Integer.valueOf(0)});
    m.addRow(new Object[]{"Grade C", Integer.valueOf(0)});
    m.addRow(new Object[]{"Grade D", Integer.valueOf(0)});
    m.addRow(new Object[]{"Grade F", Integer.valueOf(0)});
    }//GEN-LAST:event_btnGenerateReportActionPerformed

