    private void loadSemesters() {
    cmbSemester.removeAllItems();
    if (ctx == null) return;
    java.util.List<String> terms = new java.util.ArrayList<String>(ctx.getAllSchedules().keySet());
    java.util.Collections.sort(terms);
    for (String t : terms) cmbSemester.addItem(t);
    if (cmbSemester.getItemCount() > 0) cmbSemester.setSelectedIndex(0);
}

private void loadCoursesForSelectedSemester() {
    cmbCourse.removeAllItems();
    String term = (String) cmbSemester.getSelectedItem();
    if (term == null || ctx == null) return;

    info5100.university.example.CourseSchedule.CourseSchedule cs = ctx.getSchedule(term);
    if (cs == null) return;

    java.util.List<info5100.university.example.CourseSchedule.CourseOffer> offers = cs.getCourseOffers();
    for (info5100.university.example.CourseSchedule.CourseOffer co : offers) {
        if (co != null && co.getFacultyProfile() == faculty) {
            cmbCourse.addItem(co.getCourseNumber());
        }
    }
    if (cmbCourse.getItemCount() == 0) cmbCourse.addItem("(none)");
}

